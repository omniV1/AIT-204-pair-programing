from app.text_generator import TextGenerator


# ─── PYDANTIC MODELS (Request/Response Schemas) ──────────────────────────────
# Pydantic models define the shape of API request and response bodies.
# FastAPI uses these for automatic validation and documentation.

class GenerateRequest(BaseModel):
    """Schema for text generation requests."""
    seed_text: str = Field(
        ...,
        min_length=1,
        max_length=500,
        description="Starting text for generation",
        examples=["the cat sat on"]
    )
    num_words: int = Field(
        default=50,
        ge=1,
        le=500,
        description="Number of words to generate"
    )
    temperature: float = Field(
        default=1.0,
        ge=0.1,
        le=3.0,
        description="Sampling temperature: 0.5=conservative, 1.0=balanced, 1.5=creative"
    )

    @field_validator('seed_text')
    @classmethod
    def seed_text_not_empty(cls, v):
        if not v.strip():
            raise ValueError('seed_text cannot be empty or whitespace only')
        return v.strip()


class GenerateResponse(BaseModel):
    """Schema for text generation responses."""
    seed_text: str
    generated_text: str
    num_words_requested: int
    temperature: float
    model_info: dict


class ModelInfoResponse(BaseModel):
    """Schema for model information responses."""
    status: str
    vocab_size: Optional[int] = None
    sequence_length: Optional[int] = None
    total_parameters: Optional[int] = None
    layers: Optional[list] = None
    config: Optional[dict] = None



# ── Global model instance ──────────────────────────────────────────────────────
# The model is loaded once at startup and reused for all requests
text_generator: Optional[TextGenerator] = None
MODEL_DIR = os.environ.get("MODEL_DIR", "models")


# ─── STARTUP EVENT ────────────────────────────────────────────────────────────

@app.on_event("startup")
async def load_model():
    """
    Load the trained model when the server starts.

    This runs once before the server accepts any requests.
    If no trained model is found, the server starts anyway but
    generation endpoints will return a 503 error.
    """
    global text_generator
    text_generator = TextGenerator()

    model_path = os.path.join(MODEL_DIR, 'model.pt')
    if os.path.exists(model_path):
        try:
            text_generator.load(MODEL_DIR)
            print(f"Model loaded successfully from {MODEL_DIR}/")
            info = text_generator.get_model_info()
            print(f"  Vocabulary size: {info.get('vocab_size', 'N/A')}")
            print(f"  Total parameters: {info.get('total_parameters', 'N/A'):,}")
        except Exception as e:
            print(f"Failed to load model: {e}")
            print("  Start the server anyway -- train a model first using train.py")
            text_generator = None
    else:
        print(f"No trained model found at {model_path}")
        print("  Run 'python app/train.py' to train a model first")
        text_generator = None


